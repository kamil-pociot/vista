#!/bin/sh
# Writes Formula/vista.rb for release vX.Y.Z from the checksums its assets
# carry (built by .github/workflows/release.yml on the tag).
#   packaging/update-formula.sh 0.1.0
set -eu
version="${1:?usage: $0 VERSION (e.g. 0.1.0)}"
repo="kamil-pociot/term-vista"
base="https://github.com/$repo/releases/download/v$version"
sha() {
  curl -fsSL "$base/vista-v$version-$1.tar.gz.sha256" | cut -d' ' -f1
}
arm=$(sha aarch64-apple-darwin)
intel=$(sha x86_64-apple-darwin)
linux=$(sha x86_64-unknown-linux-gnu)
dir=$(dirname "$0")/../Formula
mkdir -p "$dir"
cat > "$dir/vista.rb" <<RUBY
# Generated by packaging/update-formula.sh $version; don't edit by hand.
class Vista < Formula
  desc "Lean, keyboard-driven terminal take on IntelliJ: tree, viewer, search, git, diffs"
  homepage "https://github.com/$repo"
  version "$version"
  license "MIT"

  on_macos do
    on_arm do
      url "$base/vista-v$version-aarch64-apple-darwin.tar.gz"
      sha256 "$arm"
    end
    on_intel do
      url "$base/vista-v$version-x86_64-apple-darwin.tar.gz"
      sha256 "$intel"
    end
  end

  on_linux do
    url "$base/vista-v$version-x86_64-unknown-linux-gnu.tar.gz"
    sha256 "$linux"
  end

  depends_on "git"

  def install
    bin.install "vista"
  end

  def caveats
    <<~EOS
      For editing inside vista, install Neovim 0.10+: brew install neovim
    EOS
  end

  test do
    assert_match "vista #{version}", shell_output("#{bin}/vista --version")
  end
end
RUBY
echo "wrote $dir/vista.rb for v$version"
